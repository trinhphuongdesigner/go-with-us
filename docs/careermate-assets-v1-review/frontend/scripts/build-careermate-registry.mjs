import { readFile, writeFile, stat } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const frontend = fileURLToPath(new URL('../', import.meta.url));
const root = path.join(frontend, 'public/brand/careermate/v1');
const { assets: vectors, palette } = JSON.parse(await readFile(path.join(root, 'vectors.json'), 'utf8'));
let characters = [];
try {
  characters = JSON.parse(await readFile(path.join(root, 'characters.json'), 'utf8')).assets;
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
}
const entries = [...vectors.filter((asset) => asset.category !== 'icons'), ...characters];
for (const asset of entries) {
  await stat(path.join(frontend, 'public', asset.src));
}
await writeFile(path.join(root, 'manifest.json'), JSON.stringify({ version: 1, palette, assets: [...vectors, ...characters] }, null, 2) + '\n');
await writeFile(path.join(frontend, 'src/lib/careermateAssets.ts'), `// Generated by scripts/build-careermate-registry.mjs.\nexport const careermateAssets = ${JSON.stringify(Object.fromEntries(entries.map((asset) => [asset.id, asset])), null, 2)} as const;\nexport type CareerMateAssetName = keyof typeof careermateAssets;\n`);
console.log(`Asset registry contains ${entries.length} illustrations/characters and ${vectors.length - entries.length + characters.length} icons.`);
